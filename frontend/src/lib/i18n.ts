export function normalizeLang(value: unknown): Lang {
  return value === 'id' ? 'id' : 'en';
}

export function initialLang(): Lang {
  try {
    const stored = readPreference(LANG_STORAGE_KEY);
    if (stored === 'en' || stored === 'id') return stored;
  } catch { /* Storage may be disabled. */ }
  const browser = typeof navigator !== 'undefined' ? String(navigator.language ?? '') : '';
  return browser.toLowerCase().startsWith('id') ? 'id' : 'en';
}

export function storeLang(lang: Lang): void {
  // localStorage, copied to the console server; writePreference never throws.
  writePreference(LANG_STORAGE_KEY, lang);
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = DICTIONARIES[lang][key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export function gateReasonLabel(lang: Lang, reason: string): string {
  if (lang === 'id') return GATE_REASON_LABELS_ID[reason] ?? GATE_REASON_LABELS[reason] ?? reason;
  return GATE_REASON_LABELS[reason] ?? GATE_REASON_LABELS_EN_EXTRA[reason] ?? reason;
}

export interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

export const I18nContext = createContext<I18nValue>({
  lang: 'en',
  setLang: () => undefined,
  t: (key, vars) => translate('en', key, vars),
});

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
