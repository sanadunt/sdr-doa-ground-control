export function receiverLanguage(value: unknown): ReceiverLanguage {
	return value === 'id' ? 'id' : 'en';
}

/** Locale for calendar and date labels; English keeps the browser's own locale. */
export function receiverDateLocale(language: ReceiverLanguage): string | undefined {
	return language === 'id' ? 'id-ID' : undefined;
}

export function translateReceiver(language: ReceiverLanguage, text: string): string {
	return language === 'id' ? RECEIVER_INDONESIAN[text] ?? text : text;
}

/** Translates a message shown to the operator; unknown text, such as upstream error detail, stays English. */
export function translateReceiverMessage(language: ReceiverLanguage, message: string): string {
	if (language !== 'id' || !message) return message;
	const exact = RECEIVER_INDONESIAN[message];
	if (exact !== undefined) return exact;
	for (const [pattern, template] of RECEIVER_INDONESIAN_PATTERNS) {
		const match = pattern.exec(message);
		if (!match) continue;
		return template.replace(/\{(t?)(\d)\}/g, (_, translate: string, index: string) => {
			const group = match[Number(index)] ?? '';
			return translate ? translateReceiverMessage(language, group) : group;
		});
	}
	return message;
}

export const i18nMethods = {
	t(this: AppInstance, text: string): string {
		return translateReceiver(this.uiLanguage, text);
	},
	tm(this: AppInstance, message: string): string {
		return translateReceiverMessage(this.uiLanguage, message);
	},
};
