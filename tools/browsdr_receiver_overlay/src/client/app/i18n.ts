export function receiverLanguage(value: unknown): ReceiverLanguage {
	return value === 'id' ? 'id' : 'en';
}

export function translateReceiver(language: ReceiverLanguage, text: string): string {
	return language === 'id' ? RECEIVER_INDONESIAN[text] ?? text : text;
}

export const i18nMethods = {
	t(this: AppInstance, text: string): string {
		return translateReceiver(this.uiLanguage, text);
	},
};
